/// 10초 대기 후 강제로 플레이어의 순서를 결정하고 역순으로 메인 씬에 반환합니다.
/// </summary>
public class MiniGameTestScenario : MonoBehaviour
{
    [Header("미니게임 진행 시간")]
    public float waitDelay = 10f;
    [Header("보상 아이템 목록")]
    public YutItem[] rewardItems; // 인스펙터에서 아이템 에셋들을 할당해주세요

    private void Start()
    {
        Debug.Log("[MiniGameTestScenario] 미니게임 시작. 10초 대기...");
        StartCoroutine(RunMiniGameRoutine());
    }

    private IEnumerator RunMiniGameRoutine()
    {
        yield return new WaitForSeconds(waitDelay);

        Debug.Log("[MiniGameTestScenario] 미니게임 종료. 순위를 결정합니다.");
        
        // 현재 몇 인 플레이인지 확인하기 위해 YutGameTurn에 접근
        YutGameTurn mainGameTurn = FindAnyObjectByType<YutGameTurn>();
        int pCount = mainGameTurn != null ? mainGameTurn.playerCount : 2;

        // 임시로 역순 순위 설정 (예: 4인 -> 3, 2, 1, 0)
        int[] newOrder = new int[pCount];
        for (int i = 0; i < pCount; i++)
        {
            newOrder[i] = pCount - 1 - i;
        }

        // 1, 2등에게 랜덤 아이템 보상 지급
        if (mainGameTurn != null && rewardItems != null && rewardItems.Length > 0)
        {
            // 최소 1등, 최대 2등까지만 보상 (플레이어 수에 따라 조절)
            int rewardLimit = Mathf.Min(2, pCount); 
            for (int i = 0; i < rewardLimit; i++)
            {
                int playerIndex = newOrder[i];
                if (playerIndex >= 0 && playerIndex < mainGameTurn.players.Length)
                {
                    GameObject playerObj = mainGameTurn.players[playerIndex];
                    if (playerObj != null)
                    {
                        YutInventory inv = playerObj.GetComponent<YutInventory>();
                        if (inv != null)
                        {
                            YutItem randomItem = rewardItems[Random.Range(0, rewardItems.Length)];
                            inv.AddItem(randomItem);
                            Debug.Log($"[미니게임 보상] 플레이어{playerIndex + 1} ({i + 1}등)에게 '{randomItem.itemName}' 아이템 지급!");
                        }
                    }
                }
            }
        }

        if (MiniGameTransitionManager.Instance != null)
        {
            MiniGameTransitionManager.Instance.EndMiniGame(newOrder, "miniGameSceneTest");
        }
        else
        {
            Debug.LogError("[MiniGameTestScenario] MiniGameTransitionManager를 찾을 수 없습니다!");
        }
    }
}
